// scripts/post-pr-comment.js
import { Octokit } from '@octokit/rest';

async function main() {
  try {
    // Extract environment variables
    const GITHUB_TOKEN = process.env.GITHUB_TOKEN;
    const GITHUB_REPOSITORY = process.env.GITHUB_REPOSITORY;
    const GITHUB_EVENT_PATH = process.env.GITHUB_EVENT_PATH;
    const CF_ACCOUNT_ID = process.env.CF_ACCOUNT_ID || '';
    const R2_BUCKET = process.env.R2_BUCKET || 'gl-artifacts-prod';
    const GITHUB_SHA = process.env.GITHUB_SHA;
    
    console.log('Posting PR comment with preview link...');
    
    if (!GITHUB_TOKEN) {
      throw new Error('GITHUB_TOKEN is required');
    }
    
    if (!GITHUB_REPOSITORY) {
      throw new Error('GITHUB_REPOSITORY is required');
    }
    
    if (!GITHUB_SHA) {
      throw new Error('GITHUB_SHA is required');
    }
    
    // Parse repository owner and name
    const [owner, repo] = GITHUB_REPOSITORY.split('/');
    
    // Initialize GitHub client
    const octokit = new Octokit({
      auth: GITHUB_TOKEN
    });
    
    // Determine PR number from GitHub event context
    // For simplicity in this example, we're using the SHA
    // A more robust approach would parse GITHUB_EVENT_PATH for the PR number
    
    // Generate preview URL
    const sanitizedAccountId = CF_ACCOUNT_ID.replace(/\\.+$/, '');
    const previewKey = `${GITHUB_SHA}.html`;
    const previewUrl = `https://${sanitizedAccountId}.r2.cloudflarestorage.com/${R2_BUCKET}/${previewKey}`;
    
    // Create the comment body
    const commentBody = `## 🚀 Preview Ready!
    
Preview this build at: [${previewUrl}](${previewUrl})

*Generated by CI/CD preview pipeline at commit ${GITHUB_SHA}*`;
    
    // List pull requests to find one containing this commit
    const prs = await octokit.pulls.list({
      owner,
      repo,
      state: 'open'
    });
    
    // Find PR that contains this commit
    // Note: This is a simplified approach - in production you'd want to use GitHub's API
    // to find the exact PR associated with this commit
    
    // For this demonstration, we'll just post to the first open PR
    if (prs.data.length > 0) {
      const prNumber = prs.data[0].number;
      
      console.log(`Posting comment to PR #${prNumber}`);
      
      // Post the comment to the PR
      await octokit.issues.createComment({
        owner,
        repo,
        issue_number: prNumber,
        body: commentBody
      });
      
      console.log('Comment posted successfully!');
    } else {
      console.log('No open PRs found to comment on');
    }
  } catch (error) {
    console.error('Error posting PR comment:', error);
    process.exit(1);
  }
}

main().catch(error => {
  console.error('Unhandled error:', error);
  process.exit(1);
});
