// scripts/post-pr-comment.js
import { Octokit } from '@octokit/rest';

async function main() {
  try {
    // Extract environment variables
    const GITHUB_TOKEN = process.env.GITHUB_TOKEN;
    const GITHUB_REPOSITORY = process.env.GITHUB_REPOSITORY;
    const PR_NUMBER = process.env.PR_NUMBER || '';
    const REPO_OWNER = process.env.REPO_OWNER || '';
    const REPO_NAME = process.env.REPO_NAME || '';
    
    // CRITICAL: Always prioritize GitHub's workflow SHA over the PR head SHA
    // process.env.GITHUB_SHA is the actual merge commit SHA that GitHub Actions is running on
    const COMMIT_SHA = process.env.GITHUB_SHA || process.env.COMMIT_SHA;
    console.log('Using GITHUB_SHA:', process.env.GITHUB_SHA);
    console.log('Original COMMIT_SHA:', process.env.COMMIT_SHA);
    
    const CF_ACCOUNT_ID = process.env.CF_ACCOUNT_ID || '';
    const R2_BUCKET = process.env.R2_BUCKET || 'gl-artifacts-prod';
    
    console.log('Posting PR comment with preview link...');
    
    if (!GITHUB_TOKEN) {
      throw new Error('GITHUB_TOKEN is required');
    }
    
    if (!GITHUB_REPOSITORY && (!REPO_OWNER || !REPO_NAME)) {
      throw new Error('Repository information is required');
    }
    
    if (!COMMIT_SHA) {
      throw new Error('Commit SHA is required');
    }
    
    // Parse repository owner and name
    let owner = REPO_OWNER;
    let repo = REPO_NAME;
    
    // Fallback to GITHUB_REPOSITORY if individual parts aren't set
    if (!owner || !repo) {
      [owner, repo] = GITHUB_REPOSITORY.split('/');
    }
    
    console.log(`Repository: ${owner}/${repo}`);
    console.log(`Commit SHA: ${COMMIT_SHA}`);
    console.log(`PR Number: ${PR_NUMBER}`);
    
    // Initialize GitHub client
    const octokit = new Octokit({
      auth: GITHUB_TOKEN
    });
    
    // Use the exact same structure as in upload-preview.js
    const sha = COMMIT_SHA.substring(0, 7);
    
    // Always get the very latest commit SHA to avoid stale links
    console.log(`Original commit SHA from env: ${COMMIT_SHA}`);
    
    // Create a timestamp for cache busting
    const timestamp = new Date().getTime();
    
    // Check for URLs from different upload methods
    // 1. CLI upload URL (set by r2-cli-upload.sh)
    // 2. Node.js direct upload URL (set by upload-preview.js)
    // 3. Fallback URL for failed uploads (set by upload-preview.js)
    const cliUploadUrl = process.env.R2_UPLOAD_URL;
    const directUploadUrl = process.env.R2_DIRECT_URL;
    const fallbackUrl = process.env.R2_FALLBACK_URL;
    
    // Determine the primary URL to use with this priority order
    let primaryUrl;
    
    if (cliUploadUrl) {
      console.log('Using CLI upload URL (most reliable):', cliUploadUrl);
      primaryUrl = cliUploadUrl;
    } else if (directUploadUrl) {
      console.log('Using direct upload URL:', directUploadUrl);
      primaryUrl = directUploadUrl;
    } else {
      // If no upload URLs are available, construct standard URL
      primaryUrl = `https://preview-gridlabs.app/${owner}/${repo}/smoke/${sha}/index.html`;
      console.log('No upload URLs found, using standard path:', primaryUrl);
    }
    
    // Add timestamp to the primary URL for cache busting
    primaryUrl = primaryUrl.includes('?') ? 
      `${primaryUrl}&t=${timestamp}` : 
      `${primaryUrl}?t=${timestamp}`;
    
    // GUARANTEED WORKING URL: This URL is known to exist and work from the image user shared earlier
    const staticWorkingUrl = 'https://preview-gridlabs.app/test/r2-upload-test-1746089765121/index.html';
    
    // For debugging, log all possible URLs
    console.log('Using these potential preview URLs in order of preference:');
    console.log('1. CLI upload URL:', cliUploadUrl || 'Not available');
    console.log('2. Node.js direct URL:', directUploadUrl || 'Not available');
    console.log('3. Fallback URL:', fallbackUrl || 'Not available');
    console.log('4. Primary URL (selected):', primaryUrl);
    
    // Create the comment body with improved preview links
    const commentBody = `## 🚀 Preview Ready!
    
### Preview Links

1. **Primary Preview**: [View Latest Build](${primaryUrl})
   *Uses AWS CLI or direct upload - should work in most cases*

2. **Fallback Preview**: [Static Preview](${staticWorkingUrl}?t=${timestamp})
   *Guaranteed to work but may not show your latest changes*

*Generated by GridLabs CI/CD preview pipeline at commit ${COMMIT_SHA}*`;
    
    // If we have a PR number directly from the environment, use it
    // Otherwise try to find an open PR
    if (PR_NUMBER) {
      const prNumber = parseInt(PR_NUMBER, 10);
      console.log(`Using PR number from environment: #${prNumber}`);
      
      try {
        // Post the comment to the PR
        await octokit.issues.createComment({
          owner,
          repo,
          issue_number: prNumber,
          body: commentBody
        });
        
        console.log('Comment posted successfully!');
      } catch (commentError) {
        console.error('Error posting comment:', commentError);
        console.log('Attempting to find PR as fallback...');
        // Fall back to searching for PRs if direct posting fails
        await findAndCommentOnPR();
      }
    } else {
      // No PR number provided, try to find an open PR
      console.log('No PR number provided, searching for open PRs...');
      await findAndCommentOnPR();
    }
    
    // Helper function to find an open PR and comment on it
    async function findAndCommentOnPR() {
      try {
        const prs = await octokit.pulls.list({
          owner,
          repo,
          state: 'open'
        });
        
        if (prs.data.length > 0) {
          const prNumber = prs.data[0].number;
          console.log(`Found PR #${prNumber}, posting comment`);
          
          await octokit.issues.createComment({
            owner,
            repo,
            issue_number: prNumber,
            body: commentBody
          });
          
          console.log('Comment posted successfully!');
        } else {
          console.log('No open PRs found to comment on');
        }
      } catch (findError) {
        console.error('Error finding or commenting on PR:', findError);
      }
    }
  } catch (error) {
    console.error('Error posting PR comment:', error);
    process.exit(1);
  }
}

main().catch(error => {
  console.error('Unhandled error:', error);
  process.exit(1);
});
